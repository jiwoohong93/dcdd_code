#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -x "$ROOT/.conda/bin/python" ]]; then
  DEFAULT_PYTHON="$ROOT/.conda/bin/python"
else
  DEFAULT_PYTHON="$(command -v python3 || command -v python)"
fi
PYTHON="${PYTHON:-$DEFAULT_PYTHON}"

: "${DATAROOT:?Set DATAROOT to a dataset containing train/ with images}"

MODEL_NAME="${MODEL_NAME:-black-forest-labs/FLUX.1-Fill-dev}"
JANUS_MODEL="${JANUS_MODEL:-deepseek-ai/Janus-Pro-7B}"
OUTPUT_DIR="${OUTPUT_DIR:-$ROOT/trained-flux_janus-pro-7b}"
RESUME_FROM="${RESUME_FROM:-}"
CALIBRATION_FILE="${CALIBRATION_FILE:-}"

# Published Janus-Pro-7B DCDD configuration. A calibration file generated by
# janus_calibration_analysis.sh may override these values.
JANUS_SIMILARITY="${JANUS_SIMILARITY:-cosine}"
JANUS_TEMPERATURE="${JANUS_TEMPERATURE:-1.0000}"
JANUS_COSINE_SCALE="${JANUS_COSINE_SCALE:-29.0381}"
JANUS_LABEL_SMOOTHING_EPS="${JANUS_LABEL_SMOOTHING_EPS:-0.0100}"
if [[ -n "$CALIBRATION_FILE" ]]; then
  if [[ ! -f "$CALIBRATION_FILE" ]]; then
    echo "Calibration file not found: $CALIBRATION_FILE" >&2
    exit 1
  fi
  # shellcheck disable=SC1090
  source "$CALIBRATION_FILE"
fi

GPU="${GPU:-0,1,2,3}"
NUM_PROCESSES="${NUM_PROCESSES:-4}"
MAIN_PROCESS_PORT="${MAIN_PROCESS_PORT:-29500}"
TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-1}"
GRADIENT_ACCUMULATION_STEPS="${GRADIENT_ACCUMULATION_STEPS:-8}"
LEARNING_RATE="${LEARNING_RATE:-2e-5}"
MAX_TRAIN_STEPS="${MAX_TRAIN_STEPS:-50000}"
CHECKPOINTING_STEPS="${CHECKPOINTING_STEPS:-10000}"
SEED="${SEED:-42}"
REPORT_TO="${REPORT_TO:-none}"
TRACKER_PROJECT_NAME="${TRACKER_PROJECT_NAME:-dcdd}"
TRACKER_RUN_NAME="${TRACKER_RUN_NAME:-}"
LOGGING_STEPS="${LOGGING_STEPS:-1}"

mkdir -p "$OUTPUT_DIR"
if [[ -z "$RESUME_FROM" && -f "$OUTPUT_DIR/run_config.json" && "${ALLOW_EXISTING_OUTPUT:-0}" != "1" ]]; then
  echo "Refusing to reuse an existing run directory: $OUTPUT_DIR" >&2
  echo "Set RESUME_FROM to a checkpoint or choose a new OUTPUT_DIR." >&2
  exit 1
fi

RESUME_ARGS=()
if [[ -n "$RESUME_FROM" ]]; then
  if [[ ! -d "$RESUME_FROM" ]]; then
    echo "Resume checkpoint not found: $RESUME_FROM" >&2
    exit 1
  fi
  RESUME_ARGS+=(--resume_from="$RESUME_FROM")
fi

CUDA_VISIBLE_DEVICES="$GPU" "$PYTHON" -m accelerate.commands.launch \
  --config_file "$ROOT/accelerate_config.yaml" \
  --num_processes "$NUM_PROCESSES" \
  --main_process_port "$MAIN_PROCESS_PORT" \
  "$ROOT/train_flux_janus-pro-7b.py" \
  --pretrained_model_name_or_path="$MODEL_NAME" \
  --dataroot="$DATAROOT" \
  --output_dir="$OUTPUT_DIR" \
  "${RESUME_ARGS[@]}" \
  --mixed_precision=bf16 \
  --train_batch_size="$TRAIN_BATCH_SIZE" \
  --gradient_accumulation_steps="$GRADIENT_ACCUMULATION_STEPS" \
  --use_8bit_adam \
  --learning_rate="$LEARNING_RATE" \
  --lr_scheduler=constant \
  --lr_warmup_steps=0 \
  --max_train_steps="$MAX_TRAIN_STEPS" \
  --seed="$SEED" \
  --size=384 \
  --max_sequence_length=512 \
  --checkpointing_steps="$CHECKPOINTING_STEPS" \
  --ema_decay=0.999 \
  --grad_checkpointing \
  --report_to="$REPORT_TO" \
  --tracker_project_name="$TRACKER_PROJECT_NAME" \
  --tracker_run_name="$TRACKER_RUN_NAME" \
  --logging_steps="$LOGGING_STEPS" \
  --janus_model="$JANUS_MODEL" \
  --janus_similarity="$JANUS_SIMILARITY" \
  --janus_temperature="$JANUS_TEMPERATURE" \
  --janus_cosine_scale="$JANUS_COSINE_SCALE" \
  --janus_label_smoothing_eps="$JANUS_LABEL_SMOOTHING_EPS"
